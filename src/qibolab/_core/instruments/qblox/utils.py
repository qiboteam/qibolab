from functools import reduce
from typing import cast

import numpy as np

from qibolab._core.components import (
    AcquisitionConfig,
    Config,
    Configs,
    OscillatorConfig,
)
from qibolab._core.execution_parameters import AveragingMode, ExecutionParameters
from qibolab._core.identifier import ChannelId, Result
from qibolab._core.pulses import Acquisition, Readout
from qibolab._core.sequence import PulseSequence
from qibolab._core.sweeper import ParallelSweepers

from .limits import ACQUISITION_MEMORY


def per_shot_memory(
    sequence: PulseSequence,
    sweepers: list[ParallelSweepers],
    options: ExecutionParameters,
) -> int:
    """Compute the memory per shot."""
    # If options.averaging_mode.average, options.bins(sweepers) returns only sweep
    # dimensions (no shots dimension). In that case we must not drop the first entry.
    # Non-averaging (single shot) mode includes the shots dimension as the first entry.
    # Drop it to get only the per-shot sweep dimensions.
    bins_shape = options.bins(sweepers)
    bins = np.prod(bins_shape if options.averaging_mode.average else bins_shape[1:])
    acquisitions = max(
        sum(1 for p in pulses if isinstance(p, (Acquisition, Readout)))
        for pulses in sequence.by_channel.values()
    )
    return round(bins * acquisitions)


def batch_shots(
    sequence: PulseSequence,
    sweepers: list[ParallelSweepers],
    options: ExecutionParameters,
) -> list[int]:
    """Subdivide shots in batches.

    It assumes an integrated/discriminated acquisition, such that each
    acquisition in an individual loop accounts for a single bin.
    """
    assert options.nshots is not None

    # In this case we just pass the number of shots without subdividing based on the
    # available acquistion memory, since only a single aquisition is performed for all
    # shots.
    if options.averaging_mode.average:
        return [options.nshots]

    acq_memory_shot = per_shot_memory(sequence, sweepers, options)
    max_shots = int(ACQUISITION_MEMORY // acq_memory_shot)
    nfull, remainder = np.divmod(options.nshots, max_shots)
    return [max_shots] * int(nfull) + ([int(remainder)] if remainder != 0 else [])


def concat_shots(
    results: list[dict[int, Result]], options: ExecutionParameters
) -> dict[int, Result]:
    """Concatenate shots batches.

    It collects the measurements' batches resulting from the subdivision generated by
    the :func:`batch_shots` function.
    It assumes homogenuous batches, which are only joined over the single outermost
    dimension, and only for :obj:`AveragingMode.SINGLESHOT` acquisitions.
    """
    return (
        reduce(lambda d, e: {k: np.vstack((v, e[k])) for k, v in d.items()}, results)
        if options.averaging_mode is AveragingMode.SINGLESHOT
        else results[0]
    )


def lo_configs(
    los: dict[ChannelId, str], configs: Configs
) -> dict[ChannelId, OscillatorConfig]:
    """Extract local oscillators' configurations."""
    return {ch: cast(OscillatorConfig, configs[lo]) for ch, lo in los.items()}


def time_of_flight(config: Config, latency: int) -> float:
    """Compute the time of flight of an acquisition.

    The ``latency`` of the probe output, in ns, is supplemented to the configured
    delay, to account for the extra delay caused by pre-distortion filters, and
    consequent delay compensations. Cf.
    https://docs.qblox.com/en/v0.17.1/cluster/real_time_predistortions.html#bypasses-and-delays
    """
    assert isinstance(config, AcquisitionConfig)
    tof = config.delay + latency
    if tof < 4 or not float(tof).is_integer():
        raise ValueError(
            "Acquisition time of flight (delay + probe latency) must be an integer "
            "number of ns, of at least 4, since it becomes the duration of a Q1 "
            f"instruction. Instead found {tof}."
        )
    return tof
